param(
    [Parameter(Mandatory=$true)][string]$Clang,
    [Parameter(Mandatory=$true)][string]$SDK,
    [Parameter(Mandatory=$true)][string]$BuildDirectory
)
$ErrorActionPreference='Stop'
$repo=Split-Path $PSScriptRoot -Parent
$sdkPath=(Resolve-Path -LiteralPath $SDK).Path
$compiler=(Resolve-Path -LiteralPath $Clang).Path
$buildPath=[IO.Path]::GetFullPath($BuildDirectory)
$projectRoot=[IO.Path]::GetFullPath((Join-Path $repo '../..')).TrimEnd('\')+'\'
if (!$buildPath.StartsWith($projectRoot,[StringComparison]::OrdinalIgnoreCase)) { throw 'Build directory must be inside this project.' }
New-Item -ItemType Directory -Force -Path $buildPath | Out-Null
$env:TEMP=$buildPath; $env:TMP=$buildPath
& $compiler -target arm-apple-ios3.0 -arch armv6 -isysroot $sdkPath -Wno-incompatible-sysroot -Os -Wall -Wextra -Werror -c "$repo/tools/guest_bootstrap.c" -o "$buildPath/guest_bootstrap.o"
if ($LASTEXITCODE) { throw 'Guest bootstrap compile failed.' }
& "$sdkPath/usr/bin/ld.exe" -arch armv6 -iphoneos_version_min 3.0 -undefined dynamic_lookup -syslibroot $sdkPath -o "$buildPath/s5lbox-bootstrap" "$sdkPath/usr/lib/crt1.o" "$buildPath/guest_bootstrap.o" -lSystem -framework CoreFoundation
if ($LASTEXITCODE) { throw 'Guest bootstrap link failed.' }
# Generated data, embedded in the portable provisioning plan so every new
# jailbreak (including Packages opt-out) receives the exact same supervisor.
$bytes=[IO.File]::ReadAllBytes("$buildPath/s5lbox-bootstrap")
$hash=(Get-FileHash -LiteralPath "$buildPath/s5lbox-bootstrap" -Algorithm SHA256).Hash.ToLowerInvariant()
$lines=[Collections.Generic.List[string]]::new()
$lines.Add("/* Generated by tools/build_guest_bootstrap.ps1; source: tools/guest_bootstrap.c.")
$lines.Add(" * SHA256: $hash. Startup-object license: GuestPackageNotices.txt. */")
$lines.Add('static const uint8_t GUEST_BOOTSTRAP[] = {')
for ($at=0; $at -lt $bytes.Length; $at+=16) {
    $end=[Math]::Min($at+15,$bytes.Length-1)
    $lines.Add('    '+(($bytes[$at..$end] | ForEach-Object { '0x{0:x2}' -f $_ }) -join ',')+',')
}
$lines.Add('};')
[IO.File]::WriteAllText("$repo/app/Sources/VMGuestBootstrap.inc",($lines -join "`n")+"`n",[Text.UTF8Encoding]::new($false))
Get-FileHash -LiteralPath "$buildPath/s5lbox-bootstrap" -Algorithm SHA256
